import { runTypeLabel } from '../format'

/** How wide a pace band Garmin should accept as "on target" around each prescribed pace. */
const PACE_TOLERANCE_PCT = 0.03

const RUNNING_SPORT_TYPE = { sportTypeId: 1, sportTypeKey: 'running' }
const NO_TARGET = { workoutTargetTypeId: 1, workoutTargetTypeKey: 'no.target' }

/** m/s from a pace in sec/km. */
function speedMs(paceSecPerKm) {
  return 1000 / paceSecPerKm
}

/** Pace target as a [slower, faster] speed band, +/- PACE_TOLERANCE_PCT around the prescribed pace. */
function paceTarget(targetPaceSecPerKm) {
  const slowerPace = targetPaceSecPerKm * (1 + PACE_TOLERANCE_PCT)
  const fasterPace = targetPaceSecPerKm * (1 - PACE_TOLERANCE_PCT)
  return {
    targetType: { workoutTargetTypeId: 6, workoutTargetTypeKey: 'pace.zone' },
    targetValueOne: speedMs(slowerPace),
    targetValueTwo: speedMs(fasterPace),
  }
}

function easeStep(stepOrder, km, kind) {
  return {
    type: 'ExecutableStepDTO',
    stepOrder,
    stepType: kind === 'warmup' ? { stepTypeId: 1, stepTypeKey: 'warmup' } : { stepTypeId: 2, stepTypeKey: 'cooldown' },
    endCondition: { conditionTypeId: 3, conditionTypeKey: 'distance' },
    endConditionValue: Math.round(km * 1000),
    targetType: NO_TARGET,
  }
}

function workStep(stepOrder, km, targetPaceSecPerKm) {
  return {
    type: 'ExecutableStepDTO',
    stepOrder,
    stepType: { stepTypeId: 3, stepTypeKey: 'interval' },
    endCondition: { conditionTypeId: 3, conditionTypeKey: 'distance' },
    endConditionValue: Math.round(km * 1000),
    ...paceTarget(targetPaceSecPerKm),
  }
}

function repeatStep(stepOrder, iterations, repDistanceM, repPaceSecPerKm, recoverySec) {
  const groupId = stepOrder
  return {
    type: 'RepeatGroupDTO',
    stepOrder,
    stepType: { stepTypeId: 6, stepTypeKey: 'repeat' },
    numberOfIterations: iterations,
    smartRepeat: false,
    childStepId: groupId,
    workoutSteps: [
      {
        type: 'ExecutableStepDTO',
        stepOrder: stepOrder + 1,
        childStepId: groupId,
        stepType: { stepTypeId: 3, stepTypeKey: 'interval' },
        endCondition: { conditionTypeId: 3, conditionTypeKey: 'distance' },
        endConditionValue: Math.round(repDistanceM),
        ...paceTarget(repPaceSecPerKm),
      },
      {
        type: 'ExecutableStepDTO',
        stepOrder: stepOrder + 2,
        childStepId: groupId,
        stepType: { stepTypeId: 4, stepTypeKey: 'recovery' },
        endCondition: { conditionTypeId: 2, conditionTypeKey: 'time' },
        endConditionValue: Math.round(recoverySec),
        targetType: NO_TARGET,
      },
    ],
  }
}

export function buildGarminWorkout(runType, prescription, weekNumber) {
  let steps

  switch (prescription.kind) {
    case 'easy':
      steps = [workStep(1, prescription.distanceKm, prescription.targetPaceSecPerKm)]
      break
    case 'time_trial':
      steps = [workStep(1, prescription.distanceKm, prescription.targetPaceSecPerKm)]
      break
    case 'tempo':
      steps = [
        easeStep(1, prescription.warmupKm, 'warmup'),
        workStep(2, prescription.coreKm, prescription.targetPaceSecPerKm),
        easeStep(3, prescription.cooldownKm, 'cooldown'),
      ]
      break
    case 'interval': {
      const rep = prescription.reps[0]
      steps = [
        easeStep(1, prescription.warmupKm, 'warmup'),
        repeatStep(2, prescription.reps.length, rep.distanceM, rep.targetPaceSecPerKm, rep.recoverySec),
        easeStep(4, prescription.cooldownKm, 'cooldown'),
      ]
      break
    }
    default:
      steps = []
  }

  return {
    workoutName: `${runTypeLabel(runType)} — Week ${weekNumber}`,
    description: 'Generated by Running Coach.',
    sportType: RUNNING_SPORT_TYPE,
    workoutSegments: [{ segmentOrder: 1, sportType: RUNNING_SPORT_TYPE, workoutSteps: steps }],
  }
}
